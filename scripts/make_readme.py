def readme_name(lang: str) -> str:
    """File of a language: README.md for English, README.<lang>.md else."""
    return "README.md" if lang == "en" else f"README.{lang}.md"


def load_species(root: Path) -> dict[str, list[dict[str, Any]]]:
    """Descriptors of the catalog by kind folder, with their `id` and folder."""
    found: dict[str, list[dict[str, Any]]] = {}
    for kind in KINDS:
        entries: list[dict[str, Any]] = []
        folder = root / kind
        if folder.is_dir():
            for entry in sorted(p for p in folder.iterdir() if p.is_dir()):
                file = entry / DESCRIPTOR
                if not file.is_file():
                    continue
                desc = json.loads(file.read_text(encoding="utf-8"))
                if isinstance(desc, dict):
                    preview = f"docs/thumbs/{kind}/{entry.name}.webp"
                    entries.append(
                        {
                            **desc,
                            "id": entry.name,
                            "_kind": kind,
                            "_preview": preview if (root / preview).is_file() else "",
                        }
                    )
        found[kind] = entries
    return found


def _small(text: str) -> str:
    """Text at 75% of the size (GitHub's `sub`, `small` only takes 10% off).

    A smaller text keeps the last columns of a wide table from being cut off.
    """
    return f"<sub>{text}</sub>" if text else text


def _code_id(entry_id: str) -> str:
    """The id as code that may wrap after an underscore.

    An id is one long word: the longest one fixed the width of its column.
    `&#95;` is an underscore that Markdown cannot take for emphasis.
    """
    return "<code>" + entry_id.replace("_", "&#95;<wbr>") + "</code>"


def _cell(text: str) -> str:
    """Text safe inside a table cell."""
    return text.replace("|", "\\|").replace("\n", " ").strip()


def common_name(desc: dict[str, Any], lang: str) -> str:
    """Name in a language, else in English, else the id."""
    names = desc.get("names")
    names = names if isinstance(names, dict) else {}
    for key in (lang, "en"):
        name = names.get(key)
        if isinstance(name, str) and name.strip():
            return name.strip()
    return str(desc["id"])


def _size(desc: dict[str, Any]) -> str:
    size = desc.get("size_cm")
    if isinstance(size, list) and len(size) == 2:
        low, high = (f"{v:g}" for v in size)
        return f"{low} cm" if low == high else f"{low}–{high} cm"
    return "—"


def behaviour(desc: dict[str, Any], lang: str) -> str:
    """Swimming profile and night of a fish, in a language."""
    texts = TEXTS[lang]
    behavior = desc.get("behavior")
    profile = behavior.get("profile") if isinstance(behavior, dict) else None
    parts = []
    if profile in texts["profiles"]:
        parts.append(texts["profiles"][profile])
    if isinstance(behavior, dict) and behavior.get("burrow"):
        parts.append(texts["burrow"])
    elif isinstance(behavior, dict) and behavior.get("territory_cm"):
        parts.append(texts["territorial"])
    if desc.get("night") in texts["night"]:
        parts.append(texts["night"][desc["night"]])
    return " · ".join(parts) or "—"


def _thumb(desc: dict[str, Any]) -> str:
    if desc.get("_preview"):  # sharper than the 96x64 thumbnail of the card
        return f'<img src="{desc["_preview"]}" width="{PREVIEW_WIDTH}" alt="">'
    thumb = desc.get("thumbnail")
    if isinstance(thumb, str):
        src = f"{desc['_kind']}/{desc['id']}/{thumb}"
    elif desc["_kind"] == "fish":
        src = UNKNOWN_FISH_THUMB  # no picture yet: the default "?" fish
    else:
        return ""
    return f'<img src="{src}" width="{THUMB_WIDTH}" alt="">'


def water(desc: dict[str, Any], lang: str) -> str:
    """Waters a species lives in, in a language."""
    waters = TEXTS[lang]["waters"]
    types = desc.get("water_types")
    types = types if isinstance(types, list) else []
    return ", ".join(waters[w] for w in types if w in waters) or "—"


def plant_details(desc: dict[str, Any], lang: str) -> str:
    """Zone of a plant, in a language."""
    return TEXTS[lang]["zones"].get(desc.get("zone"), "—")


def invertebrate_details(desc: dict[str, Any], lang: str) -> str:
    """Roles and movement of an invertebrate, in a language."""
    texts = TEXTS[lang]
    roles = desc.get("role")
    parts = (
        [texts["roles"][r] for r in roles if r in texts["roles"]]
        if isinstance(roles, list)
        else []
    )
    if desc.get("movement") in texts["movements"]:
        parts.append(texts["movements"][desc["movement"]])
    return " · ".join(parts) or "—"


