def readme_name(lang: str) -> str:
    """File of a language: README.md for English, README.<lang>.md else."""
    return "README.md" if lang == "en" else f"README.{lang}.md"


def load_species(root: Path) -> dict[str, list[dict[str, Any]]]:
    """Descriptors of the catalog by kind folder, with their `id` and folder."""
    found: dict[str, list[dict[str, Any]]] = {}
    for kind in KINDS:
        entries: list[dict[str, Any]] = []
        folder = root / kind
        if folder.is_dir():
            for entry in sorted(p for p in folder.iterdir() if p.is_dir()):
                file = entry / DESCRIPTOR
                if not file.is_file():
                    continue
                desc = json.loads(file.read_text(encoding="utf-8"))
                if isinstance(desc, dict):
                    entries.append({**desc, "id": entry.name, "_kind": kind})
        found[kind] = entries
    return found


def _cell(text: str) -> str:
    """Text safe inside a table cell."""
    return text.replace("|", "\\|").replace("\n", " ").strip()


def common_name(desc: dict[str, Any], lang: str) -> str:
    """Name in a language, else in English, else the id."""
    names = desc.get("names")
    names = names if isinstance(names, dict) else {}
    for key in (lang, "en"):
        name = names.get(key)
        if isinstance(name, str) and name.strip():
            return name.strip()
    return str(desc["id"])


def _size(desc: dict[str, Any]) -> str:
    size = desc.get("size_cm")
    if isinstance(size, list) and len(size) == 2:
        low, high = (f"{v:g}" for v in size)
        return f"{low} cm" if low == high else f"{low}–{high} cm"
    return "—"


def behaviour(desc: dict[str, Any], lang: str) -> str:
    """Swimming profile and night of a fish, in a language."""
    texts = TEXTS[lang]
    behavior = desc.get("behavior")
    profile = behavior.get("profile") if isinstance(behavior, dict) else None
    parts = []
    if profile in texts["profiles"]:
        parts.append(texts["profiles"][profile])
    if isinstance(behavior, dict) and behavior.get("territory_cm"):
        parts.append(texts["territorial"])
    if desc.get("night") in texts["night"]:
        parts.append(texts["night"][desc["night"]])
    return " · ".join(parts) or "—"


def _thumb(desc: dict[str, Any]) -> str:
    thumb = desc.get("thumbnail")
    if not isinstance(thumb, str):
        return ""
    src = f"{desc['_kind']}/{desc['id']}/{thumb}"
    return f'<img src="{src}" width="{THUMB_WIDTH}" alt="">'


def species_table(entries: list[dict[str, Any]], lang: str, fish: bool) -> str:
    """Markdown table of the species of a kind, sorted by common name."""
    texts = TEXTS[lang]
    if not entries:
        return texts["none"]
    head = ["", texts["name"], texts["scientific"], texts["size"]]
    if fish:
        head.append(texts["behaviour"])
    rows = [
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
    ]
    for desc in sorted(entries, key=lambda d: common_name(d, lang).casefold()):
        scientific = desc.get("scientific")
        cells = [
            _thumb(desc),
            f"{_cell(common_name(desc, lang))}<br>`{desc['id']}`",
            f"*{_cell(scientific)}*" if isinstance(scientific, str) else "—",
            _size(desc),
        ]
        if fish:
            cells.append(_cell(behaviour(desc, lang)))
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows)


def language_bar(lang: str) -> str:
    """Flags linking to the README of every language (as in ha-reef-card)."""
    links = [
        f'[<img src="{FLAG_URL.format(FLAGS.get(other, other))}" width="5%" '
        f'alt="{TEXTS[other]["language"]}" title="{TEXTS[other]["language"]}"/>]'
        f"({readme_name(other)})"
        for other in LANGUAGES
    ]
    return " ".join(links)


def block(species: dict[str, list[dict[str, Any]]], lang: str) -> str:
    """Generated part of a README, markers included."""
    texts = TEXTS[lang]
    parts = [BEGIN, language_bar(lang), texts["intro"]]
    for kind, title in (("fish", texts["fish"]), ("corals", texts["corals"])):
        entries = species.get(kind, [])
        parts.append(f"## {title} ({len(entries)})")
        parts.append(species_table(entries, lang, fish=kind == "fish"))
    if texts["docs"]:
        parts.append(texts["docs"])
    parts.append(texts["license"])
    parts.append(END)
    return "\n\n".join(parts)


def render(root: Path) -> dict[str, str]:
    """Expected content of every README, by file name."""
    species = load_species(root)
    english = root / readme_name("en")
    current = english.read_text(encoding="utf-8") if english.is_file() else ""
    start, end = current.find(BEGIN), current.find(END)
    if start < 0 or end < start:
        raise SystemExit(
            f"{english.name}: no generated block, add the lines\n{BEGIN}\n{END}"
        )
    files = {
        english.name: current[:start] + block(species, "en") + current[end + len(END) :]
    }
    for lang in LANGUAGES:
        if lang != "en":
            files[readme_name(lang)] = (
                "# reeftank-catalog\n\n" + block(species, lang) + "\n"
            )
    return files


def outdated(root: Path) -> dict[str, str]:
    """READMEs whose content differs from the catalog, with the new content."""
    changes: dict[str, str] = {}
    for name, content in render(root).items():
        file = root / name
        if not file.is_file() or file.read_text(encoding="utf-8") != content:
            changes[name] = content
    return changes


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="catalog root (default: this repository)",
    )
    parser.add_argument(
        "--check", action="store_true", help="write nothing, fail when outdated"
    )
    args = parser.parse_args(argv)
    changes = outdated(args.root)
    if args.check:
        for name in changes:
            print(f"{name} is out of date: run scripts/make_readme.py")
        return 1 if changes else 0
    for name, content in changes.items():
        (args.root / name).write_text(content, encoding="utf-8")
        print(f"{name} updated")
    if not changes:
        print("READMEs up to date")
    return 0


