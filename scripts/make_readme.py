def is_hd(desc: dict[str, Any]) -> bool:
    """A real animation (from videos): an atlas that is not the degraded one made from a photo."""
    return bool(desc.get("atlas")) and not desc.get("degraded")


def species_table(entries: list[dict[str, Any]], lang: str, kind: str) -> str:
    """Markdown table of the species of a kind, sorted by common name."""
    texts = TEXTS[lang]
    if not entries:
        return texts["none"]
    details = DETAILS.get(kind)
    head = [
        COLUMN_SPACER,
        *(_small(texts[key]) for key in ("name", "scientific", "water", "size")),
    ]
    if details:
        head.append(_small(texts[details[0]]))
    if kind == "fish":
        head.append("HD")
    rows = [
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
    ]
    for desc in sorted(entries, key=lambda d: common_name(d, lang).casefold()):
        scientific = desc.get("scientific")
        cells = [
            _thumb(desc),
            _small(f"{_cell(common_name(desc, lang))}<br>{_code_id(desc['id'])}"),
            _small(f"*{_cell(scientific)}*" if isinstance(scientific, str) else "—"),
            _small(_cell(water(desc, lang))),
            _small(_size(desc)),
        ]
        if details:
            cells.append(_small(_cell(details[1](desc, lang))))
        if kind == "fish":
            cells.append(HD_MARK if is_hd(desc) else "")
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows)


def language_bar(lang: str) -> str:
    """Flags linking to the README of every language (as in ha-reef-card)."""
    links = [
        f'[<img src="{FLAG_URL.format(FLAGS.get(other, other))}" width="5%" '
        f'alt="{TEXTS[other]["language"]}" title="{TEXTS[other]["language"]}"/>]'
        f"({readme_name(other)})"
        for other in LANGUAGES
    ]
    return " ".join(links)


def ld_twin(src: str) -> str:
    """The low-definition twin of a demo picture (the atlas of a single photo)."""
    stem, dot, ext = src.rpartition(".")
    return f"{stem}{DEMO_LD_SUFFIX}{dot}{ext}"


def demo(lang: str) -> str:
    """The "How it works" part: two species, from videos (HD) and from a photo (LD)."""
    title, text, names = DEMO[lang]
    sentence, hd, ld = DEMO_LD[lang]
    head = "<th></th>" + "".join(f"<th><sub>{name}</sub></th>" for name in names)
    rows = [f"<tr>{head}</tr>"]
    for label, twin in ((hd, False), (ld, True)):
        cells = "".join(
            f'<td align="center"><img src="{ld_twin(src) if twin else src}" '
            f'width="{DEMO_WIDTH}" alt="{name} — {label}"/></td>'
            for (src, _), name in zip(DEMO_IMAGES, names, strict=True)
        )
        rows.append(f"<tr><td><sub>{label}</sub></td>{cells}</tr>")
    return f"## {title}\n\n{text}\n\n{sentence}\n\n<table>{''.join(rows)}</table>"


def block(species: dict[str, list[dict[str, Any]]], lang: str) -> str:
    """Generated part of a README, markers included."""
    texts = TEXTS[lang]
    parts = [
        BEGIN,
        f"> {texts['ecosystem']}",
        language_bar(lang),
        texts["intro"],
        demo(lang),
    ]
    for kind in KINDS:
        entries = species.get(kind, [])
        parts.append(f"## {texts[kind]} ({len(entries)})")
        if kind == "fish" and entries:
            parts.append(HD_NOTE[lang])
        parts.append(species_table(entries, lang, kind))
    if texts["docs"]:
        parts.append(texts["docs"])
    parts.append(texts["license"])
    parts.append(END)
    return "\n\n".join(parts)


def render(root: Path) -> dict[str, str]:
    """Expected content of every README, by file name."""
    species = load_species(root)
    english = root / readme_name("en")
    current = english.read_text(encoding="utf-8") if english.is_file() else ""
    start, end = current.find(BEGIN), current.find(END)
    if start < 0 or end < start:
        raise SystemExit(
            f"{english.name}: no generated block, add the lines\n{BEGIN}\n{END}"
        )
    files = {
        english.name: current[:start] + block(species, "en") + current[end + len(END) :]
    }
    for lang in LANGUAGES:
        if lang != "en":
            name = readme_name(lang)
            existing = root / name
            files[name] = (
                "# reeftank-catalog\n\n"
                + block(species, lang)
                + "\n\n"
                + ecosystem(
                    existing.read_text(encoding="utf-8") if existing.is_file() else ""
                )
                + "\n"
            )
    return files


def ecosystem(current: str) -> str:
    """The "Related projects" block of a README, or its empty markers.

    The block is filled by gen_ecosystem.py of the reeftank repository, which
    CI does not have: a translated README, written entirely here, carries it
    over rather than dropping it.
    """
    start, end = current.find(ECO_BEGIN), current.find(ECO_END)
    if start < 0 or end < start:
        return f"{ECO_BEGIN}\n{ECO_END}"
    return current[start : end + len(ECO_END)]


def outdated(root: Path) -> dict[str, str]:
    """READMEs whose content differs from the catalog, with the new content."""
    changes: dict[str, str] = {}
    for name, content in render(root).items():
        file = root / name
        if not file.is_file() or file.read_text(encoding="utf-8") != content:
            changes[name] = content
    return changes


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="catalog root (default: this repository)",
    )
    parser.add_argument(
        "--check", action="store_true", help="write nothing, fail when outdated"
    )
    args = parser.parse_args(argv)
    changes = outdated(args.root)
    if args.check:
        for name in changes:
            print(f"{name} is out of date: run scripts/make_readme.py")
        return 1 if changes else 0
    for name, content in changes.items():
        (args.root / name).write_text(content, encoding="utf-8")
        print(f"{name} updated")
    if not changes:
        print("READMEs up to date")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
